// TestE2EVoiceMessageSTT sends an envelope with Type=TypeVoice and a fake audio
// attachment. The voice pipeline transcribes it to "transcribed text" via the
// StubSTTProvider. Verifies the FakeModel received text containing the transcription.
func TestE2EVoiceMessageSTT(t *testing.T) {
	p := setupPipelineWithOpts(t, pipelineOpts{
		WithVoice: true,
		Responses: []agent.Response{
			finalResponse("I heard you say something."),
		},
	})

	env := channel.Envelope{
		ID:        "voice-1",
		Channel:   "webchat",
		AccountID: "user-voice",
		Type:      channel.TypeVoice,
		Attachments: []channel.Attachment{{
			Type:     channel.TypeVoice,
			MimeType: "audio/ogg",
			Data:     []byte("fake-audio-data"),
		}},
		Timestamp: time.Now(),
	}

	if err := p.sendEnvelope(t, env); err != nil {
		t.Fatalf("sendEnvelope: %v", err)
	}

	// Verify the model was called.
	if p.Fake.CallCount() != 1 {
		t.Fatalf("model calls = %d, want 1", p.Fake.CallCount())
	}

	// Verify the transcription was passed to the model.
	calls := p.Fake.Calls()
	found := false
	for _, msg := range calls[0] {
		if strings.Contains(msg.Content, "transcribed text") {
			found = true
			break
		}
	}
	if !found {
		t.Error("model did not receive 'transcribed text' in its messages")
	}

	// Verify response was sent.
	resp := p.lastResponse(t)
	if resp != "I heard you say something." {
		t.Errorf("response = %q", resp)
	}
}

// TestE2EVoiceResponseTTS sends a voice envelope and verifies the response's
// OutgoingMessage has voice attachments (TTS audio) generated by StubTTSProvider.
func TestE2EVoiceResponseTTS(t *testing.T) {
	p := setupPipelineWithOpts(t, pipelineOpts{
		WithVoice: true,
		Responses: []agent.Response{
			finalResponse("Here is your voice response."),
		},
	})

	env := channel.Envelope{
		ID:        "voice-tts-1",
		Channel:   "webchat",
		AccountID: "user-voice-tts",
		Type:      channel.TypeVoice,
		Attachments: []channel.Attachment{{
			Type:     channel.TypeVoice,
			MimeType: "audio/ogg",
			Data:     []byte("fake-audio-data"),
		}},
		Timestamp: time.Now(),
	}

	if err := p.sendEnvelope(t, env); err != nil {
		t.Fatalf("sendEnvelope: %v", err)
	}

	// Check response has attachments (TTS audio from StubTTSProvider).
	responses := p.allResponses()
	if len(responses) != 1 {
		t.Fatalf("responses = %d, want 1", len(responses))
	}

	outMsg := responses[0]
	if len(outMsg.Attachments) == 0 {
		t.Error("expected TTS audio attachment in response, got none")
	} else {
		att := outMsg.Attachments[0]
		if att.Type != channel.TypeVoice {
			t.Errorf("attachment type = %q, want %q", att.Type, channel.TypeVoice)
		}
		if len(att.Data) == 0 {
			t.Error("TTS attachment has empty data")
		}
	}
}

// TestE2EMediaImageAttachment sends an envelope with an image attachment and
// WithMedia=true. The media pipeline processes the image and appends info to
