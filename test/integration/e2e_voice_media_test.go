// TestE2EVoiceNoAttachmentData sends a voice-type envelope without any
// attachment data. The voice pipeline should fail gracefully (empty audio error)
// and the router should send an error message rather than crashing.
func TestE2EVoiceTranscribeError(t *testing.T) {
	p := setupPipelineWithOpts(t, pipelineOpts{
		WithVoice: true,
		Responses: []agent.Response{
			// The model should not be called because transcription will fail
			// and produce empty text, causing the router to send an error.
			finalResponse("Should not reach here."),
		},
	})

	env := channel.Envelope{
		ID:        "voice-empty-1",
		Channel:   "webchat",
		AccountID: "user-voice-err",
		Type:      channel.TypeVoice,
		// Empty attachments: no audio data to transcribe.
		Attachments: []channel.Attachment{},
		Timestamp:   time.Now(),
	}

	// Should not return a Go-level error; the router handles it gracefully.
	err := p.sendEnvelope(t, env)
	if err != nil {
		t.Fatalf("sendEnvelope should not return error, got: %v", err)
	}

	// The router should have sent an error message (since transcription yields
	// no text). The model should NOT have been called.
	if p.Fake.CallCount() != 0 {
		t.Errorf("model calls = %d, want 0 (transcription should have failed)", p.Fake.CallCount())
	}

	// The channel should still have received a response (the error message).
	if p.responseCount() != 1 {
		t.Fatalf("responses = %d, want 1 (error message)", p.responseCount())
	}
}
